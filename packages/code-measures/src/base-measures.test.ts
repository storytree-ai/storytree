/**
 * Code measures, capability 1 · Base structure measures, contracts 1.1 to 1.6: each reading over small in-memory files
 * whose answers are worked by hand (ADR-1365). A file is its repo-relative posix path and its text.
 */
import assert from "node:assert/strict";
import { test } from "node:test";

import { churnOf, complexityOf, couplingOf, duplicationOf, functionsOf, kindOf, loosenessOf, publicSurfaceOf, sizeOf, type SourceText } from "./index.js";

const file = (path: string, lines: readonly string[]): SourceText => ({ path, text: `${lines.join("\n")}\n` });

/** Close enough for a per-1,000 figure: the same ratio, however its division is ordered. */
function near(actual: number, expected: number, what: string): void {
  assert.ok(Math.abs(actual - expected) < 1e-9, `${what}: ${actual}, expected ${expected}`);
}

test("1.1 · source files are counted apart from tests, generated and .d.ts files are in neither, and size is non-blank non-comment source lines and files, with test lines and comment share beside them", () => {
  const source = file("packages/p/src/a.ts", [
    "// One header comment line.",
    'import { x } from "./b.js";',
    "",
    "/*",
    " * A block comment of three lines.",
    " */",
    "export const y = x + 1;",
    "export function z(): number {",
    "  return y;",
    "}",
  ]); // 5 code lines, 4 comment lines
  const decoy = file("packages/p/src/b.ts", [
    "export const x = 1;",
    "// The ids below are generated at run time; do not edit them by hand.",
    "export const ids: string[] = [];",
  ]); // 2 code lines, 1 comment line: a comment that is not the leading one marks nothing generated
  const testFile = file("packages/p/src/a.test.ts", ['import assert from "node:assert/strict";', "// A comment in a test file.", "", "assert.equal(1, 1);"]);
  const genName = file("packages/p/src/schema.gen.ts", ["export const schema = { a: 1 };", "export const more = 2;"]);
  const lineMarked = file("packages/p/src/generated.ts", ["// Code generated by the schema tool. DO NOT EDIT.", "export const table = [1, 2, 3];"]);
  const blockMarked = file("packages/p/src/banner.ts", ["/* This file is generated from proto/banner.proto. */", "export const proto = 1;"]);
  const declaration = file("packages/p/src/types.d.ts", ["export declare const y: number;"]);

  assert.deepEqual(
    [source, decoy, testFile, genName, lineMarked, blockMarked, declaration].map(kindOf),
    ["source", "source", "test", "out", "out", "out", "out"],
  );
  assert.equal(kindOf({ path: "packages/p/src/c.spec.ts", text: "export {};\n" }), "test");

  assert.deepEqual(sizeOf([source, decoy, testFile, genName, lineMarked, blockMarked, declaration]), {
    files: 2,
    sourceLines: 7,
    testLines: 2,
    commentLines: 5,
    commentShare: 5 / 7,
  });
});

