test("1.4 · coupling counts the workspace packages a story's source imports (type-only and re-exports included) and those whose source imports it, not declared dependencies, own packages or tests, with instability Ce/(Ca+Ce), none when both are zero", () => {
  const story = couplingOf(["alpha", "alpha-extra"], WORKSPACE);
  assert.deepEqual([...story.dependencies].sort(), ["beta", "delta", "gamma", "theta"]);
  assert.deepEqual([...story.dependents].sort(), ["beta", "eta"]);
  assert.equal(story.instability, 4 / 6);

  assert.deepEqual(couplingOf(["delta"], WORKSPACE), { dependencies: [], dependents: ["alpha"], instability: 0 }, "a re-export imports the package it names");
  assert.deepEqual(couplingOf(["zeta"], WORKSPACE), { dependencies: [], dependents: [], instability: null }, "declared by alpha and never imported, so nobody depends on it");
});

