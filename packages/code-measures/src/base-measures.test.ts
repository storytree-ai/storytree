test("1.5 · type looseness counts any types, as and angle-bracket casts but as const, ts-ignore and ts-expect-error comments and eslint-disable comments, each per 1,000 source lines, from the syntax and not the words", () => {
  const loose = file("packages/p/src/loose.ts", [
    "/* eslint-disable no-console */", //                                        eslint-disable
    "const anyValue = 1;", //                                                    1: a name, no type
    'const label = "any";', //                                                   2: a string, no type
    'const note = "@ts-ignore eslint-disable";', //                              3: a string, no comment
    "// any word in a comment is no type", //
    "export function load(raw: any): Map<string, any> {", //                     4: an annotation and a type argument
    "  // @ts-ignore", //                                                        suppression
    "  const text = raw as string;", //                                          5: as cast
    "  // @ts-expect-error", //                                                  suppression
    "  const size = <number>raw;", //                                            6: angle-bracket cast
    '  const fixed = ["a"] as const;', //                                        7: as const, no cast
    '  const other = <const>["b"];', //                                          8: const assertion, no cast
    "  console.log(text, size, fixed, other, anyValue, label, note); // eslint-disable-line", // 9: eslint-disable-line
    "  // eslint-disable-next-line @typescript-eslint/no-unused-vars", //       eslint-disable-next-line
    "  const unused = 0;", //                                                    10
    "  return new Map();", //                                                    11
    "}", //                                                                      12 source lines
  ]);
  const read = loosenessOf([loose]);
  assert.deepEqual({ any: read.any, asCasts: read.asCasts, suppressions: read.suppressions, eslintDisables: read.eslintDisables }, { any: 2, asCasts: 2, suppressions: 2, eslintDisables: 3 });
  near(read.per1000.any, 2000 / 12, "any per 1,000");
  near(read.per1000.asCasts, 2000 / 12, "as casts per 1,000");
  near(read.per1000.suppressions, 2000 / 12, "suppressions per 1,000");
  near(read.per1000.eslintDisables, 3000 / 12, "eslint-disable lines per 1,000");
});

test("1.6 · relative churn is source lines added and deleted over source size, a pure rename adding nothing, a renamed file's history followed to its name now, with top files ranked by churn times summed complexity", () => {
  const files = [
    file("packages/p/src/a.ts", ["export function a(x: number): number {", "  if (x > 0) return x;", "  return -x;", "}"]), // complexity 1, 4 lines
    file("packages/p/src/bee.ts", ["export const b = 1;"]), // 0, 1 line
    file("packages/p/src/dee.ts", ["export function d(x: number, y: number): number {", "  for (const i of [x, y]) {", "    if (i > 0) return i;", "  }", "  return 0;", "}"]), // 3, 6 lines
    file("packages/p/src/e.ts", ["export const e = (x: boolean) => (x ? 1 : 0);"]), // 1, 1 line
    file("packages/p/src/sub/f.ts", ["export function f(a: boolean, b: boolean) {", "  return a && b;", "}"]), // 1, 3 lines
    file("packages/p/src/g.ts", ["export function g(x: number) {", "  while (x > 0) x--;", "  return x;", "}"]), // 1, 4 lines, untouched
    file("packages/p/src/a.test.ts", ['import { a } from "./a.js";', "a(1);"]),
  ]; // 19 source lines
  // git log --numstat --format= over the window, newest commit first.
  const numstat = [
    "3\t1\tpackages/p/src/a.ts",
    "5\t5\tpackages/p/src/a.test.ts",
    "",
    "0\t0\tpackages/p/src/{old.ts => bee.ts}",
    "2\t1\tpackages/p/src/{cee.ts => dee.ts}",
    "4\t0\tpackages/other/src/x.ts",
    "-\t-\tpackages/p/src/logo.png",
    "",
    "0\t0\tpackages/p/lib/e.ts => packages/p/src/e.ts",
    "1\t0\tpackages/p/src/{ => sub}/f.ts",
    "",
    "1\t1\tpackages/p/src/cee.ts",
    "4\t0\tpackages/p/lib/e.ts",
    "2\t2\tpackages/p/src/a.ts",
    "6\t0\tpackages/p/src/old.ts",
    "",
  ].join("\n");
  // a 8, bee 6 (as old.ts), dee 5 (3 + 2 as cee.ts), e 4 (as lib/e.ts), sub/f 1: 19 added, 5 deleted.
  const read = churnOf(numstat, files);
  assert.equal(read.added, 19);
  assert.equal(read.deleted, 5);
  assert.equal(read.relative, 24 / 19);
  assert.ok(read.top.length <= 10);
  assert.deepEqual(read.top.slice(0, 4), [
    { path: "packages/p/src/dee.ts", churn: 5, complexity: 3, score: 15 },
    { path: "packages/p/src/a.ts", churn: 8, complexity: 1, score: 8 },
    { path: "packages/p/src/e.ts", churn: 4, complexity: 1, score: 4 },
    { path: "packages/p/src/sub/f.ts", churn: 1, complexity: 1, score: 1 },
  ]);
});
