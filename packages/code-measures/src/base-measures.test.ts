test("1.2 · a story reads its functions' complexity p90, max and total per 1,000 source lines, their length p90 and max, and its longest source file by non-blank, non-comment lines; test files are not read", () => {
  // Eleven functions, so the 90th percentile is the tenth score by nearest rank and by interpolation alike.
  const scores = [0, 1, 1, 2, 2, 3, 3, 4, 5, 6, 12]; // sum 39; lengths are score + 3: 3 4 4 5 5 6 6 7 8 9 15, 72 lines
  const ifs = (count: number) => Array.from({ length: count }, (_, n) => `  if (x > ${n}) x--;`);
  const many = file(
    "packages/p/src/many.ts",
    scores.flatMap((score, n) => [`function f${n}(x: number): number {`, ...ifs(score), "  return x;", "}", ""]),
  );
  const commented = file("packages/p/src/commented.ts", [...Array.from({ length: 100 }, (_, n) => `// note ${n}`), "export const k = 1;"]); // 1 line
  const testFile = file("packages/p/src/many.test.ts", [
    "function tested(x: number): number {",
    ...ifs(30),
    "  return x;",
    "}",
    ...Array.from({ length: 100 }, (_, n) => `export const v${n} = ${n};`),
  ]);

  const read = complexityOf([many, commented, testFile]);
  assert.equal(read.p90, 6);
  assert.equal(read.max, 12);
  near(read.per1000, 39_000 / 73, "complexity per 1,000 source lines");
  assert.equal(read.lengthP90, 9);
  assert.equal(read.lengthMax, 15);
  assert.deepEqual(read.longestFile, { path: "packages/p/src/many.ts", lines: 72 });
});

